        <h3>4.1 Cara Membuat Kompos Sederhana dalam Pot (Takakura)</h3>
        <p>Cara ini sangat cocok untuk ibu-ibu yang hobi menanam bunga atau cabai di rumah:</p>
        <ol>
            <li>Siapkan pot berlubang atau keranjang bekas. Lapisi bagian dalamnya dengan kardus bekas.</li>
            <li>Masukkan sekam atau tanah humus di bagian paling bawah.</li>
            <li>Masukkan sampah dapur (sisa sayur, kulit buah, ampas teh/kopi) yang sudah dipotong kecil-kecil.</li>
            <li>Tutup lagi dengan selapis tanah atau kompos lama. Aduk perlahan.</li>
            <li>Tutup pot agar tidak dihinggapi lalat. Diamkan 2-3 minggu, sampah akan berubah menjadi tanah hitam (kompos) yang subur!</li>
        </ol>

        <h3 class="mt-4">4.2 Membuat Pupuk Cair Organik (POC)</h3>
        <p>Punya cucian air beras? Jangan dibuang! Air cucian beras mengandung banyak vitamin untuk tanaman.</p>
        <ul>
            <li>Tampung air cucian beras pertama ke dalam botol bekas ukuran 1,5 liter.</li>
            <li>Tambahkan 1 sendok gula pasir dan 1 sendok cairan EM4 (bisa dibeli di toko pertanian).</li>
            <li>Kocok, lalu tutup rapat. Buka tutup botol sebentar setiap hari untuk membuang gas.</li>
            <li>Setelah 7 hari, cairan siap digunakan dengan cara dicampur air biasa (perbandingan 1:10) dan disiramkan ke tanaman.</li>
        </ul>

        <h3 class="mt-4">4.3 Budidaya Maggot (BSF)</h3>
